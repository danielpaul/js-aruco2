/**
 * Regenerate src/dictionaries/*.js from the legacy CommonJS dictionary files.
 *
 * Two things happen here that used to happen at runtime:
 *   - `tau` (the minimum inter-code Hamming distance) is computed offline and
 *     baked into the data module. Seven bundled dictionaries shipped
 *     `tau: null`, which triggered an O(n^2) all-pairs comparison over strings
 *     inside the Dictionary constructor — up to 3.5 seconds of blocked main
 *     thread for ARTOOLKITPLUSBCH.
 *   - duplicate and uniform codes are reported, so dictionary defects are
 *     visible at build time instead of silently disabling error correction.
 *
 * Usage: node scripts/build-dictionaries.mjs
 */

import { createRequire } from 'node:module';
import { writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const LEGACY = join(ROOT, 'legacy');
const OUT = join(ROOT, 'src', 'dictionaries');

const { AR } = require(join(LEGACY, 'aruco.js'));
for (const f of readdirSync(join(LEGACY, 'dictionaries'))) {
  if (f.endsWith('.js')) require(join(LEGACY, 'dictionaries', f));
}

function popcount(x) {
  x = x - ((x >> 1) & 0x55555555);
  x = (x & 0x33333333) + ((x >> 2) & 0x33333333);
  x = (x + (x >> 4)) & 0x0f0f0f0f;
  return (x * 0x01010101) >> 24;
}

function bitsOf(entry, nBits) {
  const bits = new Uint8Array(nBits);
  if (typeof entry === 'number' || typeof entry === 'bigint') {
    let v = BigInt(entry);
    for (let i = nBits - 1; i >= 0; i--) { bits[i] = Number(v & 1n); v >>= 1n; }
    return bits;
  }
  if (typeof entry === 'string') {
    return bitsOf(BigInt('0x' + entry.trim().replace(/^0x/i, '').replace(/UL$/i, '')), nBits);
  }
  let b = 0;
  for (const byte of entry) {
    const remaining = nBits - b;
    if (remaining <= 0) break;
    const take = remaining > 8 ? 8 : remaining;
    for (let k = take - 1; k >= 0; k--) bits[b++] = (byte >> k) & 1;
  }
  return bits;
}

function pack(bits) {
  const lanes = Math.ceil(bits.length / 32);
  const out = new Uint32Array(lanes);
  for (let i = 0; i < bits.length; i++) if (bits[i]) out[i >> 5] |= 1 << (i & 31);
  return out;
}

function analyse(codeList, nBits) {
  const packed = codeList.map((c) => pack(bitsOf(c, nBits)));
  const lanes = packed[0].length;
  const seen = new Map();
  const duplicates = [];
  const uniform = [];
  for (let i = 0; i < packed.length; i++) {
    const key = Array.from(packed[i]).join(':');
    if (seen.has(key)) duplicates.push([seen.get(key), i]);
    else seen.set(key, i);
    let ones = 0;
    for (let l = 0; l < lanes; l++) ones += popcount(packed[i][l] >>> 0);
    if (ones === 0 || ones === nBits) uniform.push(i);
  }
  let tau = Infinity;
  for (let i = 0; i < packed.length; i++) {
    for (let j = i + 1; j < packed.length; j++) {
      let d = 0;
      for (let l = 0; l < lanes; l++) d += popcount((packed[i][l] ^ packed[j][l]) >>> 0);
      if (d < tau) { tau = d; if (tau === 0) break; }
    }
    if (tau === 0) break;
  }
  return { tau: tau === Infinity ? 0 : tau, duplicates, uniform };
}

const HEADER = `/**
 * Generated by scripts/build-dictionaries.mjs — do not edit by hand.
 *
 * Side-effect free: exports data only. Nothing is registered in a global
 * registry, which is what lets \`sideEffects: false\` prune unused dictionaries
 * instead of silently dropping them at runtime.
 */
`;

function fileName(name) {
  return name.toLowerCase().replace(/_/g, '-') + '.js';
}

function emit(name, def, notes) {
  const lines = [HEADER];
  if (notes.length) lines.push('/*\n' + notes.map((n) => ' * ' + n).join('\n') + '\n */\n');
  lines.push('/** @type {import(\'../dictionary.js\').DictionaryDefinition} */');
  lines.push('export default {');
  lines.push(`  name: ${JSON.stringify(name)},`);
  lines.push(`  nBits: ${def.nBits},`);
  lines.push(`  tau: ${def.tau},`);
  lines.push(`  maxCorrectionBits: ${def.maxCorrectionBits},`);
  // Above 53 bits a numeric literal cannot be trusted to round-trip, so emit
  // hex strings instead. Only CHILITAGS (64 bits) needs this today.
  const codes = def.nBits > 53
    ? def.codeList.map((c) => typeof c === 'number'
      ? '0x' + BigInt(c).toString(16)
      : c)
    : def.codeList;
  lines.push('  codeList: ' + JSON.stringify(codes) + ',');
  lines.push('};');
  writeFileSync(join(OUT, fileName(name)), lines.join('\n') + '\n');
}

mkdirSync(OUT, { recursive: true });

// ---------------------------------------------------------------------------
// OpenCV predefined families. Each size is a prefix of the same byte list, and
// OpenCV declares maxCorrectionBits per size; we assert our derived bound
// matches so the two implementations agree on what is a valid detection.
// ---------------------------------------------------------------------------
const OPENCV_FAMILIES = [
  { base: 'ARUCO_4X4_1000', nBits: 16, sizes: [[50, 1], [100, 1], [250, 1], [1000, 0]] },
  { base: 'ARUCO_5X5_1000', nBits: 25, sizes: [[50, 3], [100, 3], [250, 2], [1000, 2]] },
  { base: 'ARUCO_6X6_1000', nBits: 36, sizes: [[50, 6], [100, 5], [250, 5], [1000, 4]] },
  { base: 'ARUCO_7X7_1000', nBits: 49, sizes: [[50, 9], [100, 8], [250, 8], [1000, 6]] },
];

const generated = [];
const report = [];

for (const fam of OPENCV_FAMILIES) {
  const src = AR.DICTIONARIES[fam.base];
  if (!src) { console.warn(`missing legacy ${fam.base}`); continue; }
  for (const [count, opencvMaxCorr] of fam.sizes) {
    const codeList = src.codeList.slice(0, count);
    const { tau, duplicates, uniform } = analyse(codeList, fam.nBits);
    const derived = Math.floor((tau - 1) / 2);
    const grid = Math.sqrt(fam.nBits);
    const name = `DICT_${grid}X${grid}_${count}`;
    const notes = [
      `OpenCV ${name}: first ${count} codes of the ${grid}x${grid} set.`,
      `Minimum inter-code Hamming distance (tau) = ${tau}.`,
      `Correctable radius floor((tau-1)/2) = ${derived}; OpenCV declares maxCorrectionBits = ${opencvMaxCorr}.`,
    ];
    if (derived !== opencvMaxCorr) {
      notes.push(`NOTE: derived bound differs from OpenCV's; using OpenCV's value for interop.`);
    }
    if (duplicates.length) notes.push(`Duplicate code pairs: ${JSON.stringify(duplicates)}`);
    if (uniform.length) notes.push(`Uniform (solid) codes: ${JSON.stringify(uniform)}`);
    emit(name, {
      nBits: fam.nBits, tau,
      maxCorrectionBits: opencvMaxCorr,
      codeList,
    }, notes);
    generated.push({ name, nBits: fam.nBits, count, tau, derived, opencv: opencvMaxCorr });
    report.push(
      `${name.padEnd(16)} codes=${String(count).padStart(4)} tau=${String(tau).padStart(2)} ` +
      `derived=${derived} opencv=${opencvMaxCorr}${derived === opencvMaxCorr ? '' : '  <-- MISMATCH'}` +
      (duplicates.length ? `  dupes=${duplicates.length}` : '') +
      (uniform.length ? `  uniform=${JSON.stringify(uniform)}` : '')
    );
  }
}

// ---------------------------------------------------------------------------
// Everything else the fork already shipped, carried over unchanged apart from
// baking tau in.
// ---------------------------------------------------------------------------
const SKIP = new Set(OPENCV_FAMILIES.map((f) => f.base));
for (const [name, src] of Object.entries(AR.DICTIONARIES)) {
  if (SKIP.has(name)) continue;
  const { tau, duplicates, uniform } = analyse(src.codeList, src.nBits);
  const derived = Math.floor((tau - 1) / 2);
  const notes = [
    `Minimum inter-code Hamming distance (tau) = ${tau}, computed offline.`,
    `Correctable radius floor((tau-1)/2) = ${derived}.`,
  ];
  if (src.tau != null && src.tau !== tau) {
    notes.push(`The pre-3.0 data declared tau: ${src.tau}; the measured value is ${tau}.`);
  }
  if (duplicates.length) {
    notes.push(`Duplicate code pairs (later id unreachable): ${JSON.stringify(duplicates)}`);
  }
  if (uniform.length) {
    notes.push(`Uniform (solid) codes: ${JSON.stringify(uniform)} — a solid quadrilateral`);
    notes.push(`decodes as these ids at distance 0 unless allowUniformCodes is false.`);
  }
  emit(name, { nBits: src.nBits, tau, maxCorrectionBits: derived, codeList: src.codeList }, notes);
  generated.push({ name, nBits: src.nBits, count: src.codeList.length, tau, derived });
  report.push(
    `${name.padEnd(22)} codes=${String(src.codeList.length).padStart(4)} tau=${String(tau).padStart(2)} ` +
    `derived=${derived}` +
    (src.tau != null && src.tau !== tau ? `  (declared ${src.tau})` : '') +
    (duplicates.length ? `  DUPES=${JSON.stringify(duplicates)}` : '') +
    (uniform.length ? `  UNIFORM=${JSON.stringify(uniform)}` : '')
  );
}

// ---------------------------------------------------------------------------
// Registry
// ---------------------------------------------------------------------------
generated.sort((a, b) => a.name.localeCompare(b.name));
const registry = [
  HEADER,
  '/** Every dictionary bundled with this package. */',
  'export const DICTIONARY_NAMES = /** @type {const} */ ([',
  ...generated.map((g) => `  ${JSON.stringify(g.name)},`),
  ']);',
  '',
  '/** Aliases kept for pre-3.0 compatibility. */',
  'export const DICTIONARY_ALIASES = {',
  "  ARUCO_4X4_1000: 'DICT_4X4_1000',",
  "  ARUCO_5X5_1000: 'DICT_5X5_1000',",
  "  ARUCO_6X6_1000: 'DICT_6X6_1000',",
  "  ARUCO_7X7_1000: 'DICT_7X7_1000',",
  '};',
  '',
  'const loaders = {',
  ...generated.map((g) => `  ${JSON.stringify(g.name)}: () => import(${JSON.stringify('./' + fileName(g.name))}),`),
  '};',
  '',
  'const cache = new Map();',
  '',
  '/**',
  ' * Load a bundled dictionary definition by name. Dynamic import, so a bundler',
  ' * code-splits each dictionary rather than putting all of them in your',
  ' * initial chunk. Import the data module directly for a static dependency.',
  ' *',
  ' * @param {string} name',
  " * @returns {Promise<import('../dictionary.js').DictionaryDefinition>}",
  ' */',
  'export async function loadDictionaryDefinition(name) {',
  '  const key = DICTIONARY_ALIASES[name] || name;',
  '  if (cache.has(key)) return cache.get(key);',
  '  const load = loaders[key];',
  '  if (!load) {',
  "    const { UnknownDictionaryError } = await import('../errors.js');",
  '    throw new UnknownDictionaryError(name, DICTIONARY_NAMES.slice());',
  '  }',
  '  const mod = await load();',
  '  cache.set(key, mod.default);',
  '  return mod.default;',
  '}',
  '',
  '/**',
  ' * Load a dictionary by name, already constructed and cached.',
  ' * @param {string} name',
  " * @returns {Promise<import('../dictionary.js').Dictionary>}",
  ' */',
  'const instances = new Map();',
  '',
  'export async function loadDictionary(name) {',
  '  const key = DICTIONARY_ALIASES[name] || name;',
  '  if (instances.has(key)) return instances.get(key);',
  '  const def = await loadDictionaryDefinition(name);',
  "  const { Dictionary } = await import('../dictionary.js');",
  '  const dict = new Dictionary(def);',
  '  instances.set(key, dict);',
  '  return dict;',
  '}',
  '',
].join('\n');

writeFileSync(join(OUT, 'index.js'), registry);

console.log(report.join('\n'));
console.log(`\n${generated.length} dictionaries written to src/dictionaries/`);
